// 100단위 → 분야 (목록에 없는 코드도 색을 맞추려고)
const GROUP_BY_HUNDRED = { 1: 'language', 2: 'music', 3: 'art', 4: 'computer', 6: 'exercise', 7: 'study' }
const groupOfCode = (code) => GROUP_BY_HUNDRED[Math.floor(code / 100)] ?? 'etc'

const BY_CODE = new Map([
  ...GROUPS.flatMap((g) => g.items.map(([code, name]) => [code, { code, name, group: g.id }])),
  ...LEGACY.map(([code, name]) => [code, { code, name, group: groupOfCode(code), legacy: true }]),
])

export const isCategory = (code) => BY_CODE.has(code)
export const categoryName = (code) => BY_CODE.get(code)?.name ?? `분류 ${code}`
export const categoryGroup = (code) => BY_CODE.get(code)?.group ?? groupOfCode(code)

